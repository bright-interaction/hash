// Merge the generated GDPR Article 13 notice strings (see i18n.a13.ts) into the
// per-locale dictionaries so the A13Notice component resolves them via $t.
for (const [code, extra] of Object.entries(a13Messages)) {
  if (dicts[code as Locale]) Object.assign(dicts[code as Locale], extra);
}

function isLocale(v: string): v is Locale {
  return Object.prototype.hasOwnProperty.call(dicts, v);
}

function detect(): Locale {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && isLocale(saved)) return saved;
  }
  if (typeof navigator !== 'undefined' && navigator.language) {
    const prefix = navigator.language.toLowerCase().split('-')[0];
    // Map common aliases to our codes.
    const alias: Record<string, Locale> = { no: 'nb', nn: 'nb' };
    if (alias[prefix]) return alias[prefix];
    if (isLocale(prefix)) return prefix;
  }
  return 'en';
}

export const locale = writable<Locale>(detect());

// initLocale re-runs detection in the browser (call from onMount) so a value
// chosen on the server (always 'en') is corrected after hydration.
export function initLocale() {
  locale.set(detect());
}

export function setLocale(l: Locale) {
  locale.set(l);
  if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, l);
}

// preferLocale applies a server-suggested locale (e.g. the sender's per-
// recipient choice) WITHOUT persisting. By default it only applies when the
// visitor has not already chosen one themselves, so a visitor's toggle wins.
//
// With { force: true } it overrides any previously saved global preference.
// The signer ceremony uses force because the sender DICTATES the document's
// language: the whole experience must open in that one language, never mixing
// a stale browser/localStorage pick (from some other document) with the
// server strings. The in-page selector still lets the signer switch live.
export function preferLocale(code: string, opts?: { force?: boolean }) {
  if (!opts?.force && typeof localStorage !== 'undefined' && localStorage.getItem(STORAGE_KEY)) return;
  if (isLocale(code)) locale.set(code);
}

export const t = derived(locale, ($l) => {
  return (key: string, params?: Record<string, string | number>): string => {
    let s = dicts[$l][key] ?? en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  };
});
